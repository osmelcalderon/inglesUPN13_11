Formas de decir "silencio" o "cállate" en inglés:
Be quiet. – Silencio. / Cállate. (Neutral y común).
Shh! – ¡Shh! (Onomatopeya para pedir silencio).
Quiet! – ¡Silencio! (Directo y firme).
Hush! – ¡Cállate! (Más suave, a veces usado con niños).
Shut up! – ¡Cállate! (Informal y directo, puede sonar grosero).
Keep it down. – Baja la voz. / Haz menos ruido.
Silence! – ¡Silencio! (Más formal o dramático, como en una sala de tribunal).
Zip it! – ¡Cállate! (Informal y coloquial).
Not a word. – Ni una palabra.
Hold your tongue. – Contén tu lengua. (Formal o literario).
Pipe down! – ¡Cállate! (Coloquial y un poco anticuado).
Mum's the word. – Silencio. (Usado para pedir discreción).
Keep quiet. – Mantén el silencio.
Put a sock in it! – ¡Cállate! (Coloquial y un poco humorístico).
Can it! – ¡Cállate! (Muy informal y directo).
Button it! – ¡Cállate! (Coloquial y directo).
Enough! – ¡Basta! (Para pedir silencio con firmeza).
Quiet down! – ¡Baja la voz!
Stop talking! – ¡Deja de hablar!
Not another word! – ¡Ni una palabra más!
Notas sobre el uso:
"Be quiet" y "Quiet" son las formas más neutrales y comunes.
"Shut up" es informal y puede sonar grosero, dependiendo del tono.
"Silence" es más formal y se usa en contextos serios o dramáticos.
"Shh" es una onomatopeya universal para pedir silencio.
Expresiones como "Zip it" o "Button it" son coloquiales y pueden usarse entre amigos o en situaciones informales.
