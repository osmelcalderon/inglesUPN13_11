¿Has estado esperando mucho? - Have you been waiting long? 
¿Qué es de tu vida? - What's been going on with you? (La traducción más natural en inglés sería algo así).
¿Te importa si voy contigo? - Do you mind if I join you? 
¿Está ocupado este asiento? - Is this seat taken? 
¿Eres de por aquí? - Are you from around here?
¿De qué os conocéis? - How do you know each other? 
¿Nos conocemos? - Have we met before? 
¿Sueles venir por aquí? - Do you come here often? 
¿Estás casado/a? - Are you married? 
¿Tienes novio/a? - Do you have a boyfriend/girlfriend? 
¿A qué te dedicas? - What do you do for a living? 
¿Cuánto tiempo llevas dedicándote a eso? - How long have you been doing that? 
¿Te apetece un café? - Would you like a coffee? (La forma "Do you fancy a coffee?" es muy británica, pero la más común sería "Would you like a coffee?")
¿Te puedo ofrecer algo de beber? - Can I get you a drink? 
¿Cómo va todo? - How's everything going? (Es más común "How's everything going?" que "How's things?")
¿Qué te pasa? - What's wrong?
¿Tienes prisa? - Are you in a hurry? 
¿Podrías decirme dónde está el baño, por favor? - Could you tell me where the bathroom is, please? 
¿Puedes vigilar mis cosas un momentito? - Can you watch my things for a moment? 
¿Sabes qué hora es? - Do you know what time it is? 
¿Sabes a qué hora cierran? - Do you know what time they close? 
¿Hasta qué hora hay metro? - Until what time does the metro run? ("Underground" es más británico, pero "metro" funciona bien en inglés general)
Perdona, ¿trabajas aquí? - Excuse me, do you work here? 
¿Me puedo probar esto, por favor? - Can I try this on, please? 
¿Cuántas croquetas te has comido? - How many croquettes have you eaten? (Para usar el presente perfecto en inglés en esta pregunta)
¿Pagamos a medias? - Shall we split the bill? 
¿Nos han cobrado por el pan? - Did they charge us for the bread? 
¿Sabes cómo llegar al centro? - Do you know how to get to the center? (Usamos "center" en inglés americano, y "centre" en inglés británico, dependiendo de la variante)
¿Viene alguien más? - Is anyone else coming? 
¿Dónde quedamos? - Where shall we meet? 
¿Me estás tomando el pelo? - Are you pulling my leg? 
¿Quedan cervezas? - Are there any beers left? 
¿Quieres cenar fuera esta noche? - Do you want to eat out tonight? 
¿Dónde has aparcado el coche? - Where did you park the car? 
¿De quién es esta chaqueta? - Whose jacket is this? 
¿Has visto mis llaves por alguna parte? - Have you seen my keys anywhere? 
¿Cómo vas a volver a casa? - How are you getting home? 
¿Quieres que te lleve? - Would you like me to take you? / Do you want me to give you a lift? 
¿Lo pasaste bien? - Did you have a good time? (Hay que agregar "a" en "good time" para que suene más natural)
¿Te importa si te llamo de vuelta? - Would you mind if I called you back?
¿Me puedes echar una mano? - Can you give me a hand? 
¿Me puedes hacer un favor? - Can you do me a favor? (La palabra "favour" se usa en inglés británico, pero "favor" es lo correcto en inglés americano)
¿Puedes hacer mi turno el viernes que viene? - Can you cover my shift next Friday? 
¿En qué consiste el trabajo? - What does the job involve? 
¿Cuántos puestos hay? - How many positions are there? 
¿Cuál es la fecha límite? - When's the deadline? 
¿Se podría posponer la fecha límite? - Would it be possible to extend the deadline? 
¿Mandaste el email? - Did you send the email? 
¿Cuánto tiempo te va a llevar? - How long will it take you? 
¿Me lo puedes explicar? - Can you explain it to me? 