Introduction to the Study of Learning

Excerpt from the text Learning Theories: An Educational Perspective, sixth edition by Dale

H. Schunk, pp. 27

The study of human learning focuses on how individuals acquire and modify their knowledge, skills, strategies, beliefs, and behaviors. Learning represents a lasting change in behavior or the ability to behave in a certain way, which results from practice or other experiences. This definition does not include temporary changes in behavior due to illness, fatigue, or drug use, nor those that reflect genetic and maturational factors, although many of these require responsive environments to manifest.

The scientific study of learning began in the writings of ancient philosophers such as Plato and Aristotle. Two relevant views on how knowledge is acquired are rationalism and empiricism. The psychological study of learning began in the late 19th century. Structuralism and functionalism were active schools of thought that emerged in the early 20th century with theorists such as Titchener, Dewey, and James, but these positions contained problems that prevented their widespread application to psychology

Theories provide frameworks for making sense of environmental observations, they also serve as a bridge between research and educational practice and as tools for organizing and translating research findings into recommendations for educational practice. Research can be of various types-correlational, experimental, and qualitative and can be conducted in laboratories or field settings. Some common ways to assess learning are direct observation, written and oral examinations, third-party ratings, and self-reports. Learning theories and educational practice are often considered separate issues, but in fact, they should complement each other. Neither is sufficient to ensure good teaching and learning. Theory alone does not fully capture the importance of situational factors; practical experience without theory is situation-specific and lacks a general framework for organizing knowledge about teaching and learning. Theory and practice help each other refine each other.

Behavioral theories explain learning in terms of observable events, while cognitive theories also consider learners' cognitions, beliefs, values, and feelings. Learning theories differ in how they address fundamental issues. Some of the most important are how learning occurs, the role of memory, the role of motivation, how transfer occurs, the processes involved in self-regulation, and the implications for instruction.
