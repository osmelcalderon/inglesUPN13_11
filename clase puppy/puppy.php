The Train
On a warm spring afternoon, Nicole and her brother went outside to play.
Nicole was eight, and her brother, Robert, was ten. “Let’s go to the bridge,” Nicole
said. “If we stand on the bridge, we can see fish in the river.” “I don’t know….”
Robert said. “Mom told us not to go on the bridge, it’s dangerous.” “Oh, come on,”
Nicole said. I’m not afraid. Are you?”
Nicole and Robert walked onto the bridge and began looking for fish in the
river. The bridge was a train bridge. Three times a day, trains went over the
bridge. But Nicole and Robert weren’t thinking about trains. They were thinking
about fish.
The children were standing in the middle of the bridge when they heard a
loud noise. “A train’s coming!” Robert yelled. “Run!” Robert ran to the end of the
bridge. He was safe.
Nicole ran, too, but she fell. She got up and continued running. “Hurry!
Hurry!” Robert yelled from the end of the bridge. “The train’s coming!” Nicole
looked behind her and saw the train. It was coming fast! Nicole ran toward her
brother. Then she fell a second time. She fell right on the track. She looked back
again at the train. The train was very close now! There was no time to get up and
run, so Nicole didn’t move. She stayed where she was- lying between the rails of
the train track. She put her head down and waited for the train to go over her.
Robert stood at the end of the bridge and screamed.
A few seconds later, all twelve cars of the train went over Nicole.
Sometimes the bottom of the train touched Nicole’s back, but she was not hurt. 
After the train went over her, Nicole stood up and yelled to Robert, “Don’t
tell Mom! Don’t tell Mom!”
Of course, Nicole’s mother found out about Nicole and the train. Nicole’s
mother was angry and happy at the same time. She was angry that Nicole went on
the bridge, but she was happy that Nicole was alive.
And Nicole? How is she? Nicole’s mother says, “Nicole is fine, but sometimes
she goes to sleep and then wakes up crying. And she doesn’t like the sound of
trains.”

