son una clase de palabras que se usan para reemplazar a un objeto que ya ha sido mencionado o que es conocido por el interlocutor. Estas palabras "sirven para evitar la repetición y agilizar el discurso".

me	me, (a) mí
you	te, ti, a ti
	lo, la, (a) usted
