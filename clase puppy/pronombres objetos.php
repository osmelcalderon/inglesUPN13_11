Directo
	Son palabras que reemplazan a la cosa o persona que recibe directamente la acción del verbo. Responden a la pregunta "¿qué?" o "¿a quién?"

	📌 Objeto directo: responde "¿qué?" o "¿a quién?" y es lo que recibe la acción.



Indirecto
	Son palabras que indican para quién o a quién se dirige la acción del verbo.

	📌 Objeto indirecto: responde "¿para quién?" o "¿a quién?" y es quien recibe el beneficio de la acción.

